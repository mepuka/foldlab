/**
 * T12 — the PProg round trip.
 *
 * The tiers above test the recognizer against probes the suite writes. This
 * one closes a LOOP between the two sides of the lane:
 *
 *   PProg  ──emitprograms──▶  VectorPrograms.ts
 *                                  │ recognize (ck and oxc)
 *                                  ▼
 *                            Lift documents
 *                                  │ canonJson
 *                                  ▼
 *                     ═══ byte-compared here ═══
 *                                  ▲
 *                                  │ Cas.Lift.encodeLift
 *   the SAME PProg ─────────────────┘
 *
 * and the Lean side closes the other half — `Cas.Lift.decodeLiftBytes` reads
 * those exact bytes back to the table they came from, executed inside
 * `lake exe emitprograms` on every registered program and proved in general
 * by `decodeLiftBytes_encodeLiftBytes`.
 *
 * So: emit a program from a `PProg`, recognize the emitted text, decode it
 * back, and the `PProg` is the one you started with. What this file
 * contributes is the RECOGNITION leg — that the harness reading the emitted
 * TypeScript answers exactly the document Lean says that table has.
 *
 * BOTH INPUTS ARE COMMITTED, and both are generated by one Lean run under a
 * byte-identity gate (`lake exe emitprograms --check`, in `check:cas`).
 * Nothing here reaches into `.staging`, so unlike `bin/main.ts gate` this
 * tier runs on a clean checkout.
 *
 * NOT a run-safety claim. TG1 stands open (`test/ledger.json`): a type-only
 * import erases at compile time, both engines agree, and the program can
 * still `ReferenceError` at runtime. Two type-blind engines agreeing, and a
 * decoder inverting an encoder, both concern SYNTAX and STRUCTURE. Green
 * here says the document survives the trip; it does not say the emitted
 * program runs.
 */
import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { canonJson, decodeVerdict, type Verdict } from "../src/contract";
import { CK, ENGINES, OXC } from "./engines";

const generated = new URL(
  "../../../library/effects/test/generated/",
  import.meta.url,
);

const programsSource = readFileSync(new URL("VectorPrograms.ts", generated), "utf8");
/** The Lean side's answer: the lift documents of the same tables, in
 * declaration order, as canonical JSON. */
const expectedDocument = readFileSync(
  new URL("VectorProgramLifts.json", generated),
  "utf8",
);

describe("T12 — PProg → emitted TypeScript → recognized → document", () => {
  it("the emitted programs are all lifts, none refused", () => {
    for (const engine of ENGINES) {
      const verdicts = engine.recognize(programsSource);
      expect(verdicts.length, engine.name).toBeGreaterThan(0);
      expect(
        verdicts.filter((v) => v.kind === "refusal").map((v) => v.name),
        engine.name,
      ).toEqual([]);
    }
  });

  it("every verdict decodes through the contract", () => {
    for (const engine of ENGINES) {
      for (const v of engine.recognize(programsSource)) {
        expect(() => decodeVerdict(v), `${engine.name}/${v.name}`).not.toThrow();
      }
    }
  });

  it("ck recognizes exactly the documents Lean emitted, byte for byte", () => {
    const verdicts: Verdict[] = CK.recognize(programsSource);
    expect(canonJson(verdicts) + "\n").toEqual(expectedDocument);
  });

  it("oxc recognizes exactly the documents Lean emitted, byte for byte", () => {
    const verdicts: Verdict[] = OXC.recognize(programsSource);
    expect(canonJson(verdicts) + "\n").toEqual(expectedDocument);
  });

  it("the committed document is itself canonical JSON (the gate's premise)", () => {
    // `canonJson` sorts keys at every level; Lean's `renderCompact` does the
    // same. If the committed bytes were not already canonical, the two
    // comparisons above could agree for the wrong reason.
    const reparsed: unknown = JSON.parse(expectedDocument);
    expect(canonJson(reparsed) + "\n").toEqual(expectedDocument);
  });
});
